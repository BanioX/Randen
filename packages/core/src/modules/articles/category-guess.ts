/**
 * Lower case, and without the accents that people leave out («entrecote» = «Entrecôte»,
 * «Gruyere» = «Gruyère»). Umlauts stay: «Öl» is not «ol».
 */
export function foldName(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-̧̃]/g, '')
    .normalize('NFC')
    .toLocaleLowerCase('de-CH')
    .trim();
}

const escapeRegExp = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** `rinds*` → the word starts with it, `*rahm` → ends with it, without a star → the whole word. */
function wordPattern(keyword: string): string {
  const open = keyword.startsWith('*');
  const close = keyword.endsWith('*');
  const core = escapeRegExp(foldName(keyword.slice(open ? 1 : 0, close ? -1 : undefined)));
  return `${open ? '[\\p{L}\\p{N}]*' : ''}${core}${close ? '[\\p{L}\\p{N}]*' : ''}`;
}

const MATCHERS: readonly (readonly [ArticleCategoryId, RegExp])[] = KEYWORDS.map(
  ([category, keywords]) => [
    category,
    new RegExp(
      `(?<![\\p{L}\\p{N}])(?:${keywords.map(wordPattern).join('|')})(?![\\p{L}\\p{N}])`,
      'u',
    ),
  ],
);

/**
 * The group of goods a name most likely belongs to: «Rindsentrecôte» → meat, «Vollrahm» →
 * dairy, «Weissmehl» → dry goods. Unknown names are `other`.
 */
export function guessCategory(name: string): ArticleCategoryId {
  const folded = foldName(name);
  for (const [category, matcher] of MATCHERS) {
    if (matcher.test(folded)) {
      return category;
    }
  }
  return 'other';
}
